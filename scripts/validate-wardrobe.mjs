import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const files = ['data.js', 'card-editions.js', 'school-data.js', 'schools.js', 'events.js', 'game.js'];
const source = files.map(name => fs.readFileSync(root + name, 'utf8')).join('\n').replace(/wire\(\);\s*newRun\(\);\s*$/, '');
vm.runInNewContext(source + `
render = () => {}; flash = () => {};
newRun();
assert.equal(S.outfits.length, 3);
assert(S.outfits.every(cells => cells.length === 7 && cells.every(c => c === null)));
assert(!fits(makeCard('casualoutfit'), 'outfit:0:0'));
S.flags.edu = 'uni'; startStage(STAGE_INDEX.university); S.modal = null;
assert.equal(S.grids.bag, S.outfits[0]);
assert.equal(S.outfits[0][0].id, 'casualoutfit');
assert.equal(S.outfits[0][2].id, 'jeans');
assert.equal(S.outfits[0][3].id, 'sneakers');
for (const [id, slot] of [['casualoutfit', 0], ['lightjacket', 1], ['jeans', 2], ['sneakers', 3]]) {
  const card = makeCard(id);
  for (let i = 0; i < 7; i++) assert.equal(fits(card, 'outfit:1:' + i), i === slot);
}
for (const i of [4, 5, 6]) assert(fits(makeCard('bracelet'), 'outfit:2:' + i));
assert(!fits(makeCard('phone'), 'outfit:0:4'));
assert(!fits(makeCard('jeans'), 'outfit:3:2'));
assert(!fits(makeCard('jeans'), 'outfit:0:7'));
const wrong = makeCard('jeans'); S.shop = [wrong]; const money = S.money;
move('shop:0', 'outfit:0:3');
assert.equal(S.money, money, 'Wrong-slot shop drop cannot charge money');
assert.equal(S.shop[0], wrong);
S.bench = [makeCard('lightjacket')];
move('bench:0', 'outfit:1:1');
assert.equal(S.bench.length, 0);
assert.equal(S.outfits[1][1].id, 'lightjacket');
assert(!placed().some(p => p.card === S.outfits[1][1]), 'Reserve outfit is not active');
assert(ownedCards().includes(S.outfits[1][1]));
assert.equal(findCardByUid(S.outfits[1][1].uid), S.outfits[1][1]);
for (let i = 0; i < 12; i++) {
  rollShop();
  assert(!S.shop.some(c => c.id === 'lightjacket'), 'Reserve clothing must be excluded from shop duplicates');
}
// Isolate outfits to verify effects and durability without unrelated cards or combos.
for (const g of ['weekday', 'weekend', 'relic']) S.grids[g].fill(null);
S.outfits.forEach(cells => cells.fill(null));
const top = makeCard('casualoutfit');
const coat = makeCard('lightjacket', 'dark');
const pants = makeCard('jeans', 'moon');
S.outfits[0][0] = top; S.outfits[1][1] = coat; S.outfits[2][2] = pants;
switchOutfit(0);
assert.equal(computeWeek().fx.stats.look, 1);
assert.equal(computeWeek().editionScores.dark, 0);
assert(!moonActive());
switchOutfit(1);
assert.equal(S.grids.bag, S.outfits[1]);
assert.equal(computeWeek().fx.stats.look, 2);
assert.equal(computeWeek().editionScores.dark, 1);
assert(!moonActive());
switchOutfit(2);
assert.equal(computeWeek().editionScores.dark, 0);
assert.equal(computeWeek().editionScores.moon, 1);
assert(moonActive());
const oldDur = [top.dur, coat.dur, pants.dur];
startWeek();
assert.equal(top.dur, oldDur[0]); assert.equal(coat.dur, oldDur[1]);
assert.equal(pants.dur, oldDur[2] - 1, 'Only the active outfit wears out');
assert.equal(S.darkScore, 0); assert.equal(S.moonScore, 1);
switchOutfit(0);
assert.equal(S.activeOutfit, 2, 'Cannot change outfit during settlement');
S.modal = null;
const unique = new Set(ownedCards().map(c => c.uid));
assert.equal(unique.size, ownedCards().length);
move('outfit:1:1', 'bench');
assert.equal(S.outfits[1][1], null);
move('bench:0', 'outfit:0:1');
assert.equal(S.outfits[0][1], coat);
assert.equal(ownedCards().filter(c => c.uid === coat.uid).length, 1, 'Moving never duplicates a physical item');
const saleMoney = S.money;
sell('outfit:0:1');
assert.equal(S.outfits[0][1], null);
assert(!findCardByUid(coat.uid));
assert.equal(S.money, saleMoney, 'Dark items retain their existing zero sale price');
S.outfits[1][1] = makeCard('lightjacket');
const oldRange = CARDS.lightjacket.st;
CARDS.lightjacket.st = [3, 3];
startStage(STAGE_INDEX.grad);
assert.equal(S.outfits[1][1], null, 'Inactive outfits are included in stage expiry');
assert.equal(S.grids.bag, S.outfits[S.activeOutfit]);
assert.equal(stageDef().labels.bag, '穿搭');
CARDS.lightjacket.st = oldRange;
newRun();
S.flags.edu = 'work'; startStage(STAGE_INDEX.grad);
assert.equal(S.outfits[0][0].id, 'casualoutfit', 'Direct employment also gets an initial outfit');
assert.equal(S.outfits[0][2].id, 'jeans');
assert.equal(S.outfits[0][3].id, 'sneakers');
newRun();
assert(S.outfits.every(cells => cells.every(c => c === null)));
console.log('Passed: 3 saved outfits × 7 typed slots, physical ownership, reserve inventory lookup, shop deduplication, active-only effects/editions/durability, switching guard, moves/sales, stage expiry, direct-work setup and restart.');
`, { assert, console });
